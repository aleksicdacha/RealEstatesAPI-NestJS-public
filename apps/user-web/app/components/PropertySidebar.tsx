export function PropertySidebar() {
  const [activeSection, setActiveSection] = useState('galerija');

  useEffect(() => {
    const observer = new IntersectionObserver(
      (entries) => {
        let currentActive = activeSection;
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            currentActive = entry.target.id;
          }
        });
        setActiveSection(currentActive);
      },
      { 
        threshold: 0.1, 
        rootMargin: '-80px 0px -80px 0px',
        root: null
      }
    );

    menuItems.forEach(({ id }) => {
      const element = document.getElementById(id);
      if (element) observer.observe(element);
    });

    return () => observer.disconnect();
  }, []);

  const handleClick = (id: string) => {
    const element = document.getElementById(id);
    if (element) {
      const offset = 100;
      const elementPosition = element.getBoundingClientRect().top;
      const offsetPosition = elementPosition + window.pageYOffset - offset;

      window.scrollTo({
        top: offsetPosition,
        behavior: 'smooth',
      });
    }
  };

  return (
    <aside className="w-20">
      <nav className="bg-white rounded-lg shadow-sm border border-gray-200 p-2">
        <ul className="space-y-3">
          {menuItems.map(({ id, icon }) => (
            <li key={id}>
              <button
                onClick={() => handleClick(id)}
                className={`w-full flex items-center justify-center py-4 px-3 rounded-md transition-all ${
                  activeSection === id
                    ? 'bg-orange-600 text-white shadow-md'
                    : 'text-gray-600 hover:bg-gray-100 hover:text-orange-600'
                }`}
                title={id}
              >
                {icon}
              </button>
            </li>
          ))}
        </ul>
      </nav>
    </aside>
  );
}
